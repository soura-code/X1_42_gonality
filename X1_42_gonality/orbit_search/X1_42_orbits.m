/*
  X1_42_orbits.m  --  orbits of Aut_{F5}(X) = <sigma_4> on the places of small
  degree of X = X1(42)/F5, saved for later reuse.
  ------------------------------------------------------------------
  For each degree v in DEGS (default 1,2,3,4,5) this script
    * computes the places of degree v (Magma's Places(AFF, v), in that order),
    * computes the exact image of every place under sigma = sigma_4,
    * checks that the images form a permutation whose cycle lengths divide 12
      (and, for v = 1, that it is the permutation found by X1_42_check_orbs.m),
    * splits the places into orbits (= cycles of the permutation, since the
      group is cyclic, generated by sigma),
    * writes everything to X1_42_orbits_d<v>.txt, including for every place the
      data needed to find it again (the place of F5(t) below it and a key).
  The saved group (X1_42_aut_F5.txt) is used; it is never recomputed.

  How the image phi(P) of a place P is found (all steps exact).  sigma is
  stored as the pull-back sigma^*, and v_{phi(P)}(f) = v_P(sigma^* f):
    1. phi(P) lies over the place of F5(t) given by the minimal polynomial over
       F5 of the residue of sigma^*(t) at P (t = infinity if sigma^*(t) has a
       pole at P); the candidates are the places of degree v over it;
    2. if several, compare keys (minimal polynomials of the residues of
       t, y, t+y, t+2y; the key of phi(P) is computed from sigma^*(t), sigma^*(y));
    3. if still several, use for each candidate Q a function u_Q with
       v_Q(u_Q) > 0 (LocalUniformizer): u_Q vanishes at phi(P) iff
       v_P(sigma^* u_Q) > 0; the vanishing pattern pins down phi(P);
    4. otherwise the place is reported as ambiguous (and the degree is not saved).

  Parallel use: the places of each degree are split round-robin into NPARTS
  parts; this job computes the images of part PART.  Normally started by
  run_orbits.sh.  By hand (in the folder with X1_42_aut_load.m and
  X1_42_aut_F5.txt):
      magma -b degs:=5 part:=0 nparts:=12 X1_42_orbits.m
  Output: X1_42_orbits_d<v>_part<k>_of_<m>.txt.  Then
      python3 X1_42_orbits_merge.py
  checks all parts and writes X1_42_orbits_d<v>.txt and X1_42_orbits_summary.txt.
  Reload later with X1_42_orbits_load.m (see that file).
  ------------------------------------------------------------------
*/
if assigned degs then DEGS := [ StringToInteger(s) : s in Split(degs, ",") ];
else DEGS := [1,2,3,4,5]; end if;
if assigned part   then PART   := StringToInteger(part);   else PART   := 0; end if;
if assigned nparts then NPARTS := StringToInteger(nparts); else NPARTS := 1; end if;
assert NPARTS ge 1 and 0 le PART and PART lt NPARTS;
printf "Part %o of %o (images of the places with index i = %o mod %o)\n", PART, NPARTS, PART+1, NPARTS;
GENIDX := 4;
printf "Orbits of <sigma_%o> on the places of degrees %o\n", GENIDX, DEGS;

// ---------------- the curve (same as all other scripts) ----------------
A<x,y> := PolynomialRing(GF(5),2);
P,homogenize := Homogenization(A);
f := x^16*y^4+4*(y+2)*y^4*x^15+(y^3+3*y^2+4*y+1)*(y+1)^2*(y+3)*y^3*x^14+4*(y^6+3*y^5+4*y^2+2*y+2)*(y+3)*y^3*x^13+3*(y^4+2*y^2+2*y+1)*(y^3+4*y^2+4*y+4)*(y+3)*y^2*x^12+2*(y+1)^2*y^2*(y^6+4*y^5+4*y^3+3*y^2+1)*x^11+3*(y^8+y^7+3*y^6+3*y^5+4*y^3+y^2+2*y+1)*y^2*x^10+4*(y^7+y^6+4*y^5+4*y^4+4*y^3+2*y+2)*(y^5+2*y^4+2*y^2+4*y+4)*y^2*x^9+(y+2)*(y^11+3*y^10+2*y^9+4*y^8+4*y^7+y^6+4*y^5+2*y^4+4*y^3+2*y^2+3*y+2)*(y^2+y+1)*y*x^8+2*(y^3+y^2+y+3)*(y+1)*(y^11+4*y^9+2*y^8+4*y^7+3*y^6+4*y^4+3*y^3+4*y^2+1)*x^7+3*(y^4+2*y^3+2*y^2+y+1)*(y^2+y+2)^2*(y^5+3*y^4+y^3+y^2+3*y+3)*y*(y+4)*x^6+4*(y^5+3*y^4+2*y^3+1)*(y^5+4*y^4+4*y^3+y^2+4)*y*(y^2+2*y+4)*(y+4)^2*x^5+(y+2)^2*(y+3)^2*y*(y+4)^5*x^4+3*(y^4+3*y^3+3*y+2)*y*(y+4)^5*x^3+3*(y+2)*y*(y+4)^5*(y^3+2*y^2+1)*x^2+2*(y^3+2*y^2+4*y+2)*y*(y+4)^6*x+(y^2+4*y+1)*y*(y+4)^7 ;
f := homogenize(f);
XF2 := Scheme(ProjectiveSpace(P),f);
FF := FunctionField(XF2);
AFF := AlgorithmicFunctionField(FF);
plc1 := Places(AFF,1);
assert Genus(AFF) eq 25 and #plc1 eq 12;

// ---------------- key functions (identical to X1_42_check_orbs.m) ----------------
EncPoly := function(g)
    c := Coefficients(g); e := 0;
    for i in [#c..1 by -1] do e := 5*e + (Integers()!c[i]); end for;
    return e + 5^(#c);
end function;
ValueAt := function(g, Q)
    try
        if Valuation(g, Q) lt 0 then return false, 0; end if;
        R := ResidueClassField(Q);
        return true, R!Evaluate(g, Q);
    catch e
        return false, 0;
    end try;
end function;
MinPolyF5 := function(a)
    k := PrimeField(Parent(a));
    try
        return MinimalPolynomial(a, k);
    catch e1
        dummy := 0;
    end try;
    return MinimalPolynomial(a);
end function;
KeyFromValues := function(a, b)
    try
        polys := [ MinPolyF5(a), MinPolyF5(b), MinPolyF5(a+b), MinPolyF5(a+2*b) ];
    catch e
        return false, 0;
    end try;
    E := 5^12; key := 0;
    for g in polys do key := key*E + EncPoly(g); end for;
    return true, key;
end function;
PlaceKey := function(gu, gw, Q)
    ok1, a := ValueAt(gu, Q); if not ok1 then return false, 0; end if;
    ok2, b := ValueAt(gw, Q); if not ok2 then return false, 0; end if;
    return KeyFromValues(a, b);
end function;
KU := SeparatingElement(AFF);
KW := AFF.1;
RatKeyLine := function()
    ks := [];
    for Q in plc1 do
        ok, k := PlaceKey(KU, KW, Q);
        Append(~ks, ok select k else -1);
    end for;
    return "RAT " cat &cat[ Sprintf("%o ", k) : k in Sort(ks) ];
end function;

load "X1_42_aut_load.m";          // TT = t, YY = y, ApplyAut, ComposeAut, LoadAutDataOpt

// data identifying a place: coefficients of the polynomial of F5(t) below it
// ([] for t = infinity), bucket code, key
PlaceData := function(Q)
    okt, at := ValueAt(TT, Q);
    if okt then
        mp := MinPolyF5(at);
        coeffs := [ Integers()!c : c in Coefficients(mp) ];
        b := EncPoly(mp);
    else
        coeffs := []; b := 0;
    end if;
    k := 0;
    if okt then
        oky, ay := ValueAt(YY, Q);
        if oky then ok, kk := KeyFromValues(at, ay); if ok then k := kk; end if; end if;
    end if;
    return coeffs, b, k;
end function;

ZeroFunction := function(Q)
    try
        u := LocalUniformizer(Q);
        if Valuation(u, Q) gt 0 then return true, u; end if;
    catch e
        dummy := 0;
    end try;
    return false, 0;
end function;

// ---------------- the generator, from the saved group ----------------
t0 := Cputime();
okA, AUTS := LoadAutDataOpt("X1_42_aut_F5.txt", false);
error if not okA, "could not load X1_42_aut_F5.txt";
GEN := AUTS[GENIDX];
pw := GEN; ord := 1;
while not (pw[1] eq TT and pw[2] eq YY) do
    pw := ComposeAut(GEN, pw); ord +:= 1;
    error if ord gt 12, "generator has order > 12";
end while;
error if ord ne 12, Sprintf("sigma_%o has order %o, not 12", GENIDX, ord);
printf "Loaded the saved group; sigma_%o has order 12 (%o s)\n", GENIDX, Round(Cputime(t0));
GT := GEN[1]; GY := GEN[2];
A4KNOWN := [9,5,2,1,12,8,11,7,3,4,10,6];     // sigma_4 on Places(AFF,1), from X1_42_check_orbs.m

summary := [];
for V in DEGS do
    printf "\n===== degree %o =====\n", V;
    t1 := Cputime();
    PL := (V eq 1) select plc1 else Places(AFF, V);
    NP := #PL;
    printf "Places of degree %o: %o (%o s)\n", V, NP, Round(Cputime(t1));

    // identification data and buckets
    COEFFS := []; BUCKET := []; FKEY := [];
    BUCKETS := AssociativeArray(Integers());
    for i in [1..NP] do
        c, b, k := PlaceData(PL[i]);
        Append(~COEFFS, c); Append(~BUCKET, b); Append(~FKEY, k);
        if IsDefined(BUCKETS, b) then
            lst := BUCKETS[b]; Append(~lst, i); BUCKETS[b] := lst;
        else
            BUCKETS[b] := [i];
        end if;
    end for;

    // images
    t1 := Cputime();
    IMG := [ 0 : i in [1..NP] ]; how := [0,0,0]; amb := 0; mine := [];
    for i in [1..NP] do
        if (i - 1) mod NPARTS ne PART then continue; end if;
        Append(~mine, i);
        Pi := PL[i];
        okt, at := ValueAt(GT, Pi);
        b := okt select EncPoly(MinPolyF5(at)) else 0;
        j := -1;
        if IsDefined(BUCKETS, b) then
            cands := BUCKETS[b];
            if #cands eq 1 then
                j := cands[1]; how[1] +:= 1;
            else
                if okt then
                    oky, ay := ValueAt(GY, Pi);
                    if oky then
                        ok, k := KeyFromValues(at, ay);
                        if ok then
                            m := [ q : q in cands | FKEY[q] eq k ];
                            if #m eq 1 then j := m[1]; how[2] +:= 1;
                            elif #m ge 2 then cands := m; end if;
                        end if;
                    end if;
                end if;
                if j eq -1 then
                    try
                        Z := []; pass := [];
                        for q in cands do
                            okz, u := ZeroFunction(PL[q]);
                            error if not okz, "no local uniformizer";
                            Append(~Z, { r : r in cands | Valuation(u, PL[r]) gt 0 });
                            Append(~pass, Valuation(ApplyAut(GEN, u), Pi) gt 0);
                        end for;
                        S := [];
                        for r in cands do
                            good := true;
                            for jj in [1..#cands] do
                                if (r in Z[jj]) ne pass[jj] then good := false; break; end if;
                            end for;
                            if good then Append(~S, r); end if;
                        end for;
                        if #S eq 1 then j := S[1]; how[3] +:= 1; end if;
                    catch e
                        dummy := 0;
                    end try;
                end if;
            end if;
        end if;
        if j eq -1 then amb +:= 1; end if;
        IMG[i] := j;
    end for;
    printf "Images: by bucket %o, by key %o, by uniformizers %o, ambiguous %o (%o s)\n",
           how[1], how[2], how[3], amb, Round(Cputime(t1));

    // checksum of the identification data (all parts must agree; detects a
    // different place order in a later session)
    MODP := 2305843009213693951; CHK := 0;
    for i in [1..NP] do
        CHK := (CHK*1000003 + (BUCKET[i] mod 1000000007) + 7*(FKEY[i] mod 1000000007)) mod MODP;
    end for;

    // ---------------- write this part ----------------
    // The orbits, the checks (permutation, cycle lengths dividing 12, degree 1
    // against X1_42_check_orbs.m) and the final file X1_42_orbits_d<v>.txt are
    // produced by X1_42_orbits_merge.py from all parts.
    OUT := Sprintf("X1_42_orbits_d%o_part%o_of_%o.txt", V, PART, NPARTS);
    F := Open(OUT, "w");
    fprintf F, "X1_42_ORBITPART v1 DEG %o GEN %o PART %o NPARTS %o COUNT %o CHECKSUM %o\n",
            V, GENIDX, PART, NPARTS, NP, CHK;
    if PART eq 0 then
        for i in [1..NP] do
            cs := "";
            for c in COEFFS[i] do cs cat:= Sprintf("%o ", c); end for;    // empty for t = infinity
            fprintf F, "P %o | %o | %o\n", i, cs, FKEY[i];
        end for;
    end if;
    for i in mine do fprintf F, "I %o %o\n", i, IMG[i]; end for;
    fprintf F, "END %o\n", #mine;
    delete F;
    line := Sprintf("degree %o, part %o of %o: %o images (bucket %o, key %o, uniformizers %o, ambiguous %o); wrote %o",
                    V, PART, NPARTS, #mine, how[1], how[2], how[3], amb, OUT);
    print line;
    Append(~summary, line);
end for;

print "\nSummary of this job:";
for s in summary do print s; end for;
print "When all parts are done:  python3 X1_42_orbits_merge.py";
quit;
